# -*- coding: utf-8 -*-
"""Build a Revit shared parameter file from parameters.json.

Revit can only add a shared parameter to a project (Manage > Project Parameters)
from a shared parameter file, and the GUIDs must match the ones the PDSO tools
look up. This module writes that file from the same parameters.json that Model
Setup reads, so the two can't drift apart.

It has no Revit or pyRevit imports, so it also runs with plain Python. Run this
file to regenerate the shipped default:

    python PDSO.extension/lib/pdso/code/setup/shared_parameter_file.py
"""

# Python standard libraries
import io
import json
import os
import re

DEFAULT_FILE_NAME = "PDSO Shared Parameters.txt"
DEFAULT_GROUP_NAME = "PDSO"

GUID_PATTERN = re.compile(r"^[0-9a-f]{8}-([0-9a-f]{4}-){3}[0-9a-f]{12}$")

# parameters.json type -> shared parameter file DATATYPE
DATA_TYPES = {
    "string": "TEXT",
    "multilineText": "MULTILINETEXT",
    "number": "NUMBER",
    "area": "AREA",
}

HEADER = [
    "# This is a Revit shared parameter file.",
    "# Do not edit manually.",
    "# Generated by PDSO Quick Setup from parameters.json.",
    "*META\tVERSION\tMINVERSION",
    "META\t2\t1",
    "*GROUP\tID\tNAME",
]
PARAM_HEADER = (
    "*PARAM\tGUID\tNAME\tDATATYPE\tDATACATEGORY\tGROUP\tVISIBLE\tDESCRIPTION"
    "\tUSERMODIFIABLE\tHIDEWHENNOEDIT"
)


def _clean(text, what):
    """Shared parameter files are tab-separated, so values can't contain tabs or newlines."""
    text = u"{}".format(text)
    if any(char in text for char in "\t\r\n"):
        raise ValueError("{} '{}' can't contain tabs or line breaks".format(what, text))
    return text


def build_shared_parameter_file(data):
    """Build the text of a shared parameter file.

    Args:
        data (dict): Parsed parameters.json.
    Returns:
        str: The file contents, with Windows line endings.
    Raises:
        ValueError: If a parameter has an unsupported type, a bad GUID, or a
            duplicate name or GUID.
    """
    group_name = _clean(
        data.get("shared_parameter_group", DEFAULT_GROUP_NAME), "Group name"
    )
    lines = list(HEADER)
    lines.append(u"GROUP\t1\t{}".format(group_name))
    lines.append(PARAM_HEADER)

    seen_names = set()
    seen_guids = set()
    for spec in data.get("parameters", []):
        name = _clean(spec["name"], "Parameter name")
        guid = u"{}".format(spec["guid"]).strip().strip("{}").lower()
        if not GUID_PATTERN.match(guid):
            raise ValueError("'{}' has an invalid GUID: {}".format(name, spec["guid"]))
        parameter_type = spec.get("type")

        if parameter_type not in DATA_TYPES:
            raise ValueError(
                "'{}' has type '{}', which a shared parameter file can't hold. "
                "Use one of: {}".format(
                    name, parameter_type, ", ".join(sorted(DATA_TYPES))
                )
            )
        if name in seen_names:
            raise ValueError("Parameter name '{}' is listed twice".format(name))
        if guid in seen_guids:
            raise ValueError("GUID {} is listed twice".format(guid))
        seen_names.add(name)
        seen_guids.add(guid)

        lines.append(
            u"\t".join(
                [
                    "PARAM",
                    guid,
                    name,
                    DATA_TYPES[parameter_type],
                    "",  # DATACATEGORY: only used by family type parameters
                    "1",  # GROUP id
                    "1" if spec.get("visible", True) else "0",
                    _clean(spec.get("description", ""), "Description"),
                    "1" if spec.get("user_modifiable", True) else "0",
                    "0",  # HIDEWHENNOEDIT
                ]
            )
        )

    return u"\r\n".join(lines) + u"\r\n"


def write_shared_parameter_file(data, path):
    """Write a shared parameter file built from parameters.json data to path."""
    text = build_shared_parameter_file(data)
    # Plain ASCII/UTF-8 without a BOM, which every Revit version reads
    with io.open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return path


if __name__ == "__main__":
    standards_dir = os.path.normpath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "standards")
    )
    with io.open(
        os.path.join(standards_dir, "parameters.json"), encoding="utf-8-sig"
    ) as source:
        parameters = json.loads(source.read())
    print(
        write_shared_parameter_file(
            parameters, os.path.join(standards_dir, DEFAULT_FILE_NAME)
        )
    )
